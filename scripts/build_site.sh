#!/usr/bin/env bash
# Builds the GitHub Pages site into $1 (default _site):
#   /            -> tiny redirect page to app/ (keeps the public link unchanged)
#   /sw.js       -> retires the old root-scoped service worker
#   /app/...     -> the app itself, with its own install scope
set -euo pipefail
out="${1:-_site}"
rm -rf "$out"
mkdir -p "$out/app"
cp -r index.html app.js styles.css sw.js kalorit.webmanifest build-info.js version.json lib vendor data icons "$out/app/"

# stamp this build: version = hash of the app's content (a README-only push changes nothing for
# users); the app compares it with version.json to update itself, and shows built_at
version="${BUILD_VERSION:-$(cd "$out/app" && find . -type f ! -name version.json ! -name build-info.js -print0 \
  | sort -z | xargs -0 sha256sum | sha256sum | cut -c1-12)}"
commit="$(git rev-parse --short HEAD 2>/dev/null || echo dev)"
built_at="${BUILD_TIME:-$(date -u +%Y-%m-%dT%H:%M:%SZ)}"
printf "// Generated by scripts/build_site.sh\nexport const BUILD = { version: '%s', commit: '%s', builtAt: '%s' };\n" \
  "$version" "$commit" "$built_at" > "$out/app/build-info.js"
printf '{"version":"%s","commit":"%s","builtAt":"%s"}\n' "$version" "$commit" "$built_at" > "$out/app/version.json"
# a cache name per build, so the browser installs a fresh service worker and cache
sed -i "s/^const VERSION = '[^']*';/const VERSION = 'kalorit-app-$version';/" "$out/app/sw.js"
cp scripts/site/index.html scripts/site/sw.js "$out/"
cp icons/icon-192.png "$out/favicon.png"
touch "$out/.nojekyll"
echo "site built in $out (version $version, $built_at)"
