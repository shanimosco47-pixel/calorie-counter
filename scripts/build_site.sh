#!/usr/bin/env bash
# Builds the GitHub Pages site into $1 (default _site):
#   /            -> tiny redirect page to app/ (keeps the public link unchanged)
#   /sw.js       -> retires the old root-scoped service worker
#   /app/...     -> the app itself, with its own install scope
set -euo pipefail
out="${1:-_site}"
rm -rf "$out"
mkdir -p "$out/app"
cp -r index.html app.js styles.css sw.js kalorit.webmanifest build-info.js version.json lib vendor data icons "$out/app/"

# stamp this deploy: the app shows it and compares it with version.json to update itself
commit="${BUILD_COMMIT:-$(git rev-parse --short HEAD 2>/dev/null || echo dev)}"
built_at="${BUILD_TIME:-$(date -u +%Y-%m-%dT%H:%M:%SZ)}"
printf "// Generated by scripts/build_site.sh\nexport const BUILD = { commit: '%s', builtAt: '%s' };\n" "$commit" "$built_at" > "$out/app/build-info.js"
printf '{"commit":"%s","builtAt":"%s"}\n' "$commit" "$built_at" > "$out/app/version.json"
# a new cache name per deploy, so the browser always installs a fresh service worker and cache
sed -i "s/^const VERSION = '[^']*';/const VERSION = 'kalorit-app-$commit';/" "$out/app/sw.js"
cp scripts/site/index.html scripts/site/sw.js "$out/"
cp icons/icon-192.png "$out/favicon.png"
touch "$out/.nojekyll"
echo "site built in $out ($commit, $built_at)"
